HashType parse_hash_type(const std::string& raw) {
    const std::string t = to_lower(trim(raw));

    if (t == "md5")                  return HashType::MD5;
    if (t == "sha1")                 return HashType::SHA1;
    if (t == "sha224")               return HashType::SHA224;
    if (t == "sha256")               return HashType::SHA256;
    if (t == "sha384")               return HashType::SHA384;
    if (t == "sha512")               return HashType::SHA512;
    if (t == "ntlm")                 return HashType::NTLM;
    if (t == "bcrypt")               return HashType::BCRYPT;
    if (t == "scrypt")               return HashType::SCRYPT;
    if (t == "argon2i")              return HashType::ARGON2I;
    if (t == "argon2d")              return HashType::ARGON2D;
    if (t == "argon2id")             return HashType::ARGON2ID;
    if (t == "kerberoast-rc4")       return HashType::KERBEROAST_RC4_HMAC;
    if (t == "kerberoast-aes128")    return HashType::KERBEROAST_AES128_CTS_HMAC;
    if (t == "kerberoast-aes256")    return HashType::KERBEROAST_AES256_CTS_HMAC;
    if (t == "kerberoast-des3")      return HashType::KERBEROAST_DES3_CBC_SHA1;

    // Fall back to the registry so any name printed by --list-hashes
    // (for example "Kerberoast-RC4-HMAC") can be used verbatim.
    auto& registry = HashRegistry::instance();
    for (HashType type : registry.list_algorithms()) {
        auto* algo = registry.get_algorithm(type);
        if (algo && to_lower(algo->name()) == t) return type;
    }

    return HashType::UNKNOWN;
}

std::string attack_name(CrackerConfig::AttackMode mode) {
    switch (mode) {
        case CrackerConfig::AttackMode::Dictionary:  return "dictionary";
        case CrackerConfig::AttackMode::BruteForce:  return "brute-force";
        case CrackerConfig::AttackMode::Mask:        return "mask";
        case CrackerConfig::AttackMode::Hybrid:      return "hybrid";
        case CrackerConfig::AttackMode::Prince:      return "prince";
        case CrackerConfig::AttackMode::Association: return "association";
    }
    return "dictionary";
}

CrackerConfig::AttackMode parse_attack_mode(const std::string& raw) {
    const std::string m = to_lower(trim(raw));

    if (m == "dict" || m == "dictionary")  return CrackerConfig::AttackMode::Dictionary;
    if (m == "brute" || m == "brute-force" || m == "bruteforce")
        return CrackerConfig::AttackMode::BruteForce;
    if (m == "mask")                       return CrackerConfig::AttackMode::Mask;
    if (m == "hybrid")                     return CrackerConfig::AttackMode::Hybrid;
    if (m == "prince")                     return CrackerConfig::AttackMode::Prince;
    if (m == "assoc" || m == "association") return CrackerConfig::AttackMode::Association;

    std::cerr << "Error: Unknown attack mode: " << raw << "\n";
    std::exit(1);
}

void list_hashes() {
    auto& registry = HashRegistry::instance();
    std::cout << "Supported Hash Types:\n"
                 "====================\n";
    for (HashType type : registry.list_algorithms()) {
        IHashAlgorithm* algo = registry.get_algorithm(type);
        if (!algo) continue;
        std::cout << "  " << std::left << std::setw(28) << algo->name()
                  << " (hashcat: " << algo->hashcat_mode() << ")\n";
    }
}

int identify_hash(const std::string& hash) {
    auto& registry = HashRegistry::instance();
    std::vector<HashType> matches = registry.identify_hash(hash);

    if (matches.empty()) {
        std::cerr << "Unknown hash type\n";
        return 1;
    }

    std::cout << "Possible hash types:\n";
    for (HashType type : matches) {
        IHashAlgorithm* algo = registry.get_algorithm(type);
        if (!algo) continue;
        std::cout << "  " << algo->name()
                  << " (hashcat mode: " << algo->hashcat_mode() << ")\n";
    }
    return 0;
}

